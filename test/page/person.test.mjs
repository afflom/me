// CO-01: the Prism used the way its owner uses it, in headless Chromium,
// generated from the coherence registry (app/specs/coherence/spec.json) and
// the surface: content comes in through every feeder the registry names that
// a test can press (files, a Takeout zip, a paste, a note in each place), and
// then every place that lists things must list something, Today must show
// today's agenda with its clash, and Ask must answer from what was kept.
// A place added without a working feeder, or an Ask that answers with
// anything but the owner's own items, fails here.
//
// pages.yml runs it on the assembled page and again on the published page.
// usage: NODE_PATH="$(npm root --global)" [PAGE_SITE=dir | PAGE_URL=url] node --test test/page/person.test.mjs
import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import test from "node:test";
import { chromium, faults, open, serve } from "../product/harness.mjs";
import { deflateRawSync, crc32 } from "node:zlib";

const { PLACES } = await import(resolve("site/surface/surface.mjs"));
const { FEEDERS } = await import(resolve("site/coherence/coherence.mjs"));

// Content only from the specifications' own examples (test/oracle/corpus.json,
// generated by tools/oracle/gen.py from pinned RFCs): nothing here is invented.
// The page's clock is set to the day those examples happen.
const { example, titleOf, expectOf } = await import(resolve("test/oracle/examples.mjs"));
const DAY = "1997-07-01T15:00:00Z";
// That day: a meeting at 19:00, then two at 20:00 that clash (RFC 5546 §4.1.1, §4.2.1, §4.2.4).
const TODAY = ["rfc5546-9", "rfc5546-6", "rfc5546-1"];
const [FIRST, CLASH_A, CLASH_B] = TODAY.map(titleOf);
const MAIL = "rfc5322-1";
const LATER = "rfc5545-1";
const CARD = "rfc6350-9";

function zip(entries) {
  const locals = [];
  const central = [];
  let offset = 0;
  for (const [name, text] of entries) {
    const raw = Buffer.from(text);
    const packed = deflateRawSync(raw);
    const nameBytes = Buffer.from(name);
    const head = Buffer.alloc(30);
    head.writeUInt32LE(0x04034b50, 0); head.writeUInt16LE(20, 4); head.writeUInt16LE(8, 8);
    head.writeUInt32LE(crc32(raw), 14); head.writeUInt32LE(packed.length, 18); head.writeUInt32LE(raw.length, 22); head.writeUInt16LE(nameBytes.length, 26);
    const dir = Buffer.alloc(46);
    dir.writeUInt32LE(0x02014b50, 0); dir.writeUInt16LE(20, 4); dir.writeUInt16LE(20, 6); dir.writeUInt16LE(8, 10);
    dir.writeUInt32LE(crc32(raw), 16); dir.writeUInt32LE(packed.length, 20); dir.writeUInt32LE(raw.length, 24); dir.writeUInt16LE(nameBytes.length, 28); dir.writeUInt32LE(offset, 42);
    locals.push(head, nameBytes, packed);
    central.push(dir, nameBytes);
    offset += 30 + nameBytes.length + packed.length;
  }
  const dirBytes = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10); end.writeUInt32LE(dirBytes.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, dirBytes, end]);
}

test("the owner brings content in, every place shows it, Today and Ask answer from it (CO-01)", async () => {
  const dir = mkdtempSync(join(tmpdir(), "person-"));
  const feed = [...TODAY.map((id) => [`${id}.ics`, example(id)]), [`${MAIL}.eml`, example(MAIL)]].map(([name, text]) => {
    const path = join(dir, name);
    writeFileSync(path, text);
    return path;
  });
  const takeout = join(dir, "takeout.zip");
  writeFileSync(takeout, zip([
    ["Takeout/Mail/All mail Including Spam and Trash.mbox", ["rfc5322-6", "rfc5322-7"].map((id, i) => `From ${i + 1}@xxx Mon Jan 1 00:00:00 2024\r\n${example(id)}`).join("\r\n")],
    ["Takeout/Calendar/Holidays.ics", example(LATER)],
    ["Takeout/Contacts/All Contacts/All Contacts.vcf", example(CARD)],
  ]));

  const server = await serve();
  const browser = await chromium.launch();
  try {
    const context = await browser.newContext({ permissions: ["clipboard-read", "clipboard-write"], timezoneId: "UTC" });
    await context.clock.install({ time: new Date(DAY) });
    const page = await context.newPage();
    const errors = faults(page);
    await open(page, server.url);
    const out = () => page.textContent("#pr-out");
    // The status line once it matches; a timeout says what it showed instead.
    const settled = (pattern) => page.waitForFunction((p) => new RegExp(p).test(document.getElementById("pr-out").textContent), pattern.source, { timeout: 30000 })
      .catch(async (error) => { throw new Error(`status never matched ${pattern}: it shows "${await out()}" (${error.message.split("\n")[0]})`); });
    // Before a new read, the status is cleared, so the count that settles is the new read's, not the last one's.
    const fresh = () => page.evaluate(() => { document.getElementById("pr-out").textContent = ""; });

    // A fresh profile opens on Today, which leads with Set up rather than nothing.
    assert.equal(await page.textContent("#pr-title"), PLACES.find((p) => p.host === "home").name);
    assert.ok(await page.locator("#pr-setup").isVisible(), "an empty Today leads with Set up");
    // Continue opens a step alone; the device row in Settings takes the person's files.
    await page.click("#pr-setup .pr-setup-go");
    await page.click('.pr-go[data-place="boundary"]');
    const picker = page.locator('#pr-settings label.pr-file input[type="file"][accept*=".ics"]').first();
    await picker.waitFor({ state: "attached", timeout: 15000 });
    // The read finishes where it was started, as the person sees it, before they go on.
    await fresh();
    await picker.setInputFiles(feed);
    await settled(/^\d+ items$/);
    assert.match(await out(), /^4 items$/);
    await page.click('.pr-go[data-place="today"]');

    // Today: the agenda first, what falls today marked, the clash marked (PrismChronology).
    await page.waitForFunction(() => document.querySelector("#pr-list .pr-section"), null, { timeout: 10000 });
    const row = (title) => page.locator("#pr-list .pr-item").filter({ has: page.locator(".pr-what").getByText(title, { exact: true }) }).first();
    assert.match(await row(FIRST).getAttribute("class"), /pr-now/);
    assert.doesNotMatch(await row(FIRST).getAttribute("class"), /pr-clash/);
    assert.match(await row(CLASH_A).getAttribute("class"), /pr-clash/);
    assert.match(await row(CLASH_B).getAttribute("class"), /pr-clash/);

    // A Takeout export, through the Boundary's own file control.
    await page.click('.pr-go[data-place="boundary"]');
    const zipInput = page.locator("#pr-settings input[type=file][accept*='.zip']");
    await zipInput.waitFor({ state: "attached", timeout: 15000 });
    await fresh();
    await zipInput.setInputFiles(takeout);
    await settled(/^\d+ items$/);
    assert.match(await out(), /^4 items$/);

    // A paste of plain words is a note.
    await page.click('.pr-go[data-place="tasks"]');
    // The words are a to-do's own summary (RFC 5545 §4, VTODO).
    const jot = titleOf("rfc5545-5");
    await page.evaluate((words) => {
      const data = new DataTransfer();
      data.setData("text/plain", words);
      document.dispatchEvent(new ClipboardEvent("paste", { clipboardData: data, bubbles: true }));
    }, jot);
    await page.waitForFunction((words) => document.getElementById("pr-list").innerText.includes(words), jot, { timeout: 10000 });

    // A note in every place that keeps notes, in that place's own name.
    for (const place of PLACES.filter((p) => p.act === "note" && p.viewpoint === "person")) {
      await page.click(`.pr-go[data-place="${place.key}"]`);
      const words = `${place.name} for ${place.key}`;
      await page.fill("#pr-act input", words);
      await page.click("#pr-act button");
      await page.waitForFunction((w) => document.getElementById("pr-list").innerText.includes(w), words, { timeout: 10000 }).catch(() => {});
    }

    // Every place that lists things lists something now; Explore finds by its search.
    const empty = [];
    for (const place of PLACES.filter((p) => p.viewpoint === "person" && p.host !== "composer" && p.show !== "settings")) {
      await page.click(`.pr-go[data-place="${place.key}"]`);
      if (place.show === "search") await page.fill("#pr-act input[type=search]", "hello");
      await page.waitForTimeout(300);
      const shown = await page.locator("#pr-list .pr-item").count();
      if (!shown) empty.push(place.key);
    }
    assert.deepEqual(empty, [], `places with nothing after every feeder ran: ${empty.join(", ")}`);
    // The mail is in Messages, and its sender in People.
    // A place draws its list after the click, so each is given time to show it.
    const lists = (text) => page.waitForFunction((t) => document.getElementById("pr-list").innerText.includes(t), text, { timeout: 10000 }).then(() => true, () => false);
    await page.click('.pr-go[data-place="conversations"]');
    assert.ok(await lists(titleOf(MAIL)), "the mail is not in Messages");
    await page.click('.pr-go[data-place="people"]');
    assert.ok(await lists(expectOf(MAIL).who), "the mail's sender is not in People");
    assert.ok(await lists(titleOf(CARD)), "the contact card is not in People");

    // Ask answers from what is kept, at once, without a model.
    const ask = async (question, expect, status = false) => {
      await page.fill("#pr-prompt", question);
      await page.click("#pr-ask-go");
      await page.waitForFunction(() => !document.getElementById("pr-ask-go").disabled, null, { timeout: 15000 });
      // A reply is the newest turn of the conversation log; a refusal is the status line's.
      const said = status ? await out() : await page.locator('.pr-chat[role="log"] .pr-turn:last-child .pr-said').innerText();
      assert.match(said, expect, `Ask "${question}" said: ${said}`);
    };
    const said = (title) => new RegExp(title.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
    await ask("What's on today?", said(FIRST));
    await ask(`When is the ${titleOf(LATER)}?`, said(titleOf(LATER)));
    await ask("Did John write?", said(titleOf(MAIL)));
    await ask("When is the conference?", said(CLASH_A));
    await ask("zebra quantum marmalade", /^Nothing you hold mentions “zebra quantum marmalade”\./u);

    // Halted, Ask shows nothing kept.
    await page.click('.pr-go[data-place="boundary"]');
    await page.check("#pr-halt");
    await ask("What's on today?", /^Paused$/, true);
    await page.uncheck("#pr-halt");

    assert.deepEqual(errors, [], `page errors: ${errors.join(" | ")}`);
    // What FEEDERS names is what this walk pressed.
    assert.ok(["files", "paste", "note"].every((key) => FEEDERS.some((f) => f.key === key)));
  } finally {
    await browser.close();
    server.close();
  }
});
