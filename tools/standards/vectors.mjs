// The acceptance vectors of a grammar's LexLean guest (Foundation.Abnf), from
// the grammar's own witnesses (tools/standards/grammar.py): each witness field
// asked of its context rule, each answered with the derivation the reference
// matcher site/read/abnf.mjs gives, as the guest writes it: one "rule,start,
// stop,depth" per named rule, depth first, positions in UTF-8 octets, rules
// by their place in the sorted rule names.
//   node tools/standards/vectors.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { abnf } from "../../site/read/abnf.mjs";

const root = new URL("../../", import.meta.url);
const spec = JSON.parse(readFileSync(new URL("app/specs/grammar/spec.json", root)));
const encoder = new TextEncoder();
const MAXIMUM = 48;
let stale = [];
for (const g of spec.grammars.filter((x) => x.vectors)) {
  const grammar = (await import(new URL(g.out, root))).default;
  const names = Object.keys(grammar.rules).sort();
  const index = Object.fromEntries(names.map((n, i) => [n, i]));
  const engine = abnf(grammar);
  const witnesses = JSON.parse(readFileSync(new URL(g.witnesses, root))).witnesses;
  const octets = (text) => { const at = [0]; for (const c of Array.from(text)) at.push(at.at(-1) + encoder.encode(c).length); return at; };
  const spans = (tree, at, depth = 0, out = []) => {
    out.push(`${index[tree.rule]},${at[tree.start]},${at[tree.end]},${depth}`);
    for (const kid of tree.kids) spans(kid, at, depth + 1, out);
    return out;
  };
  const seen = new Set();
  const examples = [];
  for (const w of Object.values(witnesses)) {
    const request = `${index[w.context]} ${w.text}`;
    if (seen.has(request)) continue;
    seen.add(request);
    const tree = engine.match(w.context, w.text);
    examples.push([request, tree ? spans(tree, octets(w.text)).join(" ") : "none"]);
  }
  // A guest's vectors are one list literal, which LexLean nests no deeper than its JSON
  // reader allows: take at most MAXIMUM, each next the one that goes through the most rules
  // not yet gone through. test/standards/grammar.test.mjs asks the built guest every witness.
  const rulesOf = (answer) => new Set(answer === "none" ? [] : answer.split(" ").map((s) => s.split(",")[0]));
  const left = new Set(examples.flatMap(([, a]) => [...rulesOf(a)]));
  const chosen = [];
  const pool = examples.map((e) => [e, rulesOf(e[1])]);
  while (left.size && chosen.length < MAXIMUM) {
    let best = null, gain = 0;
    for (const [e, rs] of pool) { const g = [...rs].filter((r) => left.has(r)).length; if (g > gain) { best = [e, rs]; gain = g; } }
    if (!best) break;
    chosen.push(best[0]);
    for (const r of best[1]) left.delete(r);
  }
  examples.splice(0, examples.length, ...chosen);
  const text = JSON.stringify({ comment: `Generated by tools/standards/vectors.mjs: the ${g.key} grammar guest's acceptance vectors, witness fields of ${g.witnesses}, each asked of its context rule, chosen to go through the most rules (test/standards/grammar.test.mjs asks the built guest every witness). Do not edit.`, examples }, null, 1) + "\n";
  const path = new URL(g.vectors, root);
  let now = null;
  try { now = readFileSync(path, "utf8"); } catch {}
  if (process.argv.includes("--check")) { if (now !== text) stale.push(g.vectors); }
  else writeFileSync(path, text);
}
if (stale.length) { console.error(`stale, run node tools/standards/vectors.mjs: ${stale.join(", ")}`); process.exit(1); }
