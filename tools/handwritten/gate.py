"""HW-01: hand-written parts of the Prism may only shrink.

    python3 -I tools/handwritten/gate.py                  measure this tree and print the totals
    python3 -I tools/handwritten/gate.py --check          and refuse what grew since the base
    --base REF       the base (default: the merge base with origin/main, or on main HEAD^1)
    --report PATH    write the inventory as Markdown; --ledger PATH  one line per file as JSON

app/specs/handwritten/spec.json says where every tracked file may come from.
A file is

  generated  when one of the spec's producers writes it: every producer runs
             in a scratch copy of the tree, and a file is generated by the
             first producer that writes it; a file the spec says is built
             (the wasm guests, the drawn images) is generated by its builder.
  upstream   when it is byte-equal to the template revision template.lock pins,
             the frame commit frame.lock pins or a vendored source, or a lock
             names it with its SHA-256 and the bytes match.
  lexlean    when it is authored in LexLean (Alex, 15 Nov 10:04Z: everything is
             required to be in prism/LexLean): the Prism's own source.
  model      when it is under one of the spec's model roots (records not yet in
             LexLean: measured as distance).
  hand       otherwise: written by hand, outside the model.

The ratchet, after verdant-resonance VR-67..VR-69 (prism/handwritten-ratchet.json):
the base revision is measured the same way, in a worktree, with this
revision's spec, so no ledger is committed and no change has one to keep
current. No file may become hand-written (a producer's plug-in excepted) and
the hand-written files together may not hold more non-comment lines.
"""
import hashlib
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

ARGS = sys.argv[1:]
SPEC_PATH = "app/specs/handwritten/spec.json"
CHECK = "--check" in ARGS


def opt(name):
    if name in ARGS:
        i = ARGS.index(name)
        if i + 1 < len(ARGS):
            return ARGS[i + 1]
    return None


# --root measures another tree (the planted-defect tests use a scratch copy).
ROOT = pathlib.Path(opt("--root") or pathlib.Path(__file__).resolve().parents[2]).resolve()
SPEC = json.loads(pathlib.Path(opt("--spec") or ROOT / SPEC_PATH).read_text())
# Measuring a base revision: a producer that fails there (it is newer than the
# base) is skipped, which only makes the base more lenient, never stricter.
TOLERANT = "--tolerant" in ARGS


NOTE = "HW-01 keeps no ledger: it measures this tree and its base alike, so there is nothing to commit for it."


def fail(lines):
    for line in lines:
        print(f"HW-01: {line}", file=sys.stderr)
    print(NOTE, file=sys.stderr)
    sys.exit(1)


def git(*args, cwd=ROOT, check=True):
    r = subprocess.run(["git", *args], cwd=cwd, capture_output=True)
    if check and r.returncode != 0:
        fail([f"git {' '.join(args)}: {r.stderr.decode(errors='replace').strip()}"])
    return r


def tracked():
    """Every file git tracks (in its index): what a build leaves behind untracked
    (.lighthouseci/, screens) is no part of the Prism. Add a new file to git to measure it."""
    out = git("ls-files", "-z", "--cached").stdout.decode()
    return sorted({p for p in out.split("\0") if p and (ROOT / p).is_file()})


def blob(data):
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def glob_re(pattern):
    """`**` crosses directories, `*` stays inside one."""
    out = ""
    i = 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out += "(?:.*/)?"
            i += 3
        elif pattern.startswith("**", i):
            out += ".*"
            i += 2
        elif pattern[i] == "*":
            out += "[^/]*"
            i += 1
        else:
            out += re.escape(pattern[i])
            i += 1
    return re.compile(out + r"\Z")


def matches(path, patterns):
    return any(glob_re(p).match(path) for p in patterns)


def class_of(path):
    for c in SPEC["classes"]:
        if matches(path, c["paths"]):
            return c["id"]
    fail([f"{path}: no class of {SPEC_PATH} holds it; add its path to one"])


def syntax(path):
    name = path.rsplit("/", 1)[-1]
    for kind, ends in SPEC["comments"].items():
        if any(name == e or name.endswith(e) for e in ends):
            return kind
    return "plain"


def code_lines(path, data):
    """Non-blank lines that are not comments, the measure verdant's ratchet
    counts (countNonCommentSourceLines). None for a file that is not text."""
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return None
    kind = syntax(path)
    if kind in ("slash", "block", "markup"):
        open_, close = ("<!--", "-->") if kind == "markup" else ("/*", "*/")
        text = re.sub(re.escape(open_) + r".*?" + re.escape(close), lambda m: "\n" * m.group(0).count("\n"), text, flags=re.S)
    count = 0
    for line in text.split("\n"):
        s = line.strip()
        if not s:
            continue
        if kind == "slash" and s.startswith("//"):
            continue
        if kind == "hash" and s.startswith("#") and not s.startswith("#!"):
            continue
        if kind == "percent" and s.startswith("%"):
            continue
        count += 1
    return count


# ---------------------------------------------------------------- measuring

def upstream_claims(files):
    """{path: source} for files byte-equal to a pinned upstream."""
    claims = {}
    for lock in SPEC["upstream"]["locks"]:
        def walk(node):
            if isinstance(node, dict):
                sha = node.get("sha256", "")
                sha = sha.split(":", 1)[-1]
                for key in ("path", "to"):
                    p = node.get(key)
                    if isinstance(p, str) and p in files and sha:
                        if hashlib.sha256((ROOT / p).read_bytes()).hexdigest() == sha:
                            claims[p] = lock
                for v in node.values():
                    walk(v)
            elif isinstance(node, list):
                for v in node:
                    walk(v)
        walk(json.loads((ROOT / lock).read_text()) if (ROOT / lock).exists() else {})
    tlock = json.loads((ROOT / SPEC["upstream"]["template"]).read_text())
    flock = json.loads((ROOT / SPEC["upstream"]["frame"]).read_text())
    pins = [
        (tlock["template_repository"], tlock["template_revision"]),
        ("https://github.com/" + flock["source"]["repository"], flock["source"]["commit"]),
    ]
    mine = {p: blob((ROOT / p).read_bytes()) for p in files}
    with tempfile.TemporaryDirectory(prefix="hw-upstream-") as tmp:
        git("init", "-q", "--bare", tmp, cwd=tmp)
        vend = SPEC["upstream"].get("vendored", [])
        for url, rev in pins + [(v["repository"], v["revision"]) for v in vend]:
            if git("-C", tmp, "fetch", "-q", "--depth=1", "--filter=blob:none", url, rev, check=False).returncode != 0:
                fail([f"cannot fetch {url} at {rev}: the full measure needs the pinned template; without the network run --check"])
            listing = git("-C", tmp, "ls-tree", "-r", rev).stdout.decode()
            for line in listing.splitlines():
                meta, p = line.split("\t", 1)
                if p in mine and meta.split()[2] == mine[p]:
                    claims.setdefault(p, f"{url}@{rev[:12]}")
                for v in vend:
                    if (url, rev) == (v["repository"], v["revision"]) and p.startswith(v["subdir"]):
                        q = v["prefix"] + p[len(v["subdir"]):]
                        if q in mine and meta.split()[2] == mine[q]:
                            claims.setdefault(q, f"{url}@{rev[:12]}")
    return claims


def generated_claims(files):
    """{path: producer} by running every producer in a scratch copy."""
    claims = {}
    # The same files under the same producers give the same answer: a run in which
    # every producer passed is kept under target/ by what it read, so the base of an
    # unchanged tree, and each planted-defect test's base, is not produced again.
    kept = (ROOT / "target").resolve() / ("handwritten-claims-%s.json" % blob(json.dumps([SPEC["producers"], SPEC["built"], [[p, blob((ROOT / p).read_bytes())] for p in files]]).encode()))
    if kept.exists():
        return json.loads(kept.read_text())
    # One fixed scratch path under target/: a producer built once (xtask)
    # keeps the path it was built in, so the copy must always be at the same place.
    work = (ROOT / "target").resolve() / "handwritten-producers"
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    try:
        for p in files:
            (work / p).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(ROOT / p, work / p)
        # Producers that list the tree with git (tools/parts/gate.py) see the same files.
        git("init", "-q", cwd=work)
        git("add", "-A", "--", ".", cwd=work)
        if (ROOT / "node_modules").exists():
            os.symlink((ROOT / "node_modules").resolve(), work / "node_modules")

        def stamp():
            return {p: (work / p).stat().st_mtime_ns for p in files}

        for prod in SPEC["producers"]:
            before = stamp()
            env = dict(os.environ, **{k: v.replace("@root", str(ROOT)) for k, v in prod.get("env", {}).items()})
            r = subprocess.run(prod["run"], cwd=work, capture_output=True, env=env)
            if r.returncode != 0 and TOLERANT:
                kept = None
                continue
            if r.returncode != 0:
                fail([f"producer {prod['id']} ({' '.join(prod['run'])}) failed:", r.stderr.decode(errors="replace")[-2000:]])
            for p, t in stamp().items():
                if t != before[p] and p not in claims:
                    claims[p] = prod["id"]
    finally:
        shutil.rmtree(work, ignore_errors=True)
    for b in SPEC["built"]:
        for p in files:
            if matches(p, b["paths"]):
                claims.setdefault(p, b["id"])
    if kept:
        kept.write_text(json.dumps(claims))
    return claims


def entry(path, provenance, source, data):
    e = {"path": path, "is": provenance}
    if source:
        e["from"] = source
    if provenance == "hand":
        e["class"] = class_of(path)
        e["lines"] = code_lines(path, data)
    # Upstream bytes and hand-made binaries are held by their blob; generated
    # files by their producer's own gate, and the model is free to change.
    if provenance == "upstream" or (provenance == "hand" and e["lines"] is None):
        e["blob"] = blob(data)
    return e


def measure():
    files = [p for p in tracked() if (ROOT / p).exists()]
    gen = generated_claims(files)
    up = upstream_claims(files)
    out = {}
    for p in files:
        data = (ROOT / p).read_bytes()
        if p in gen:
            out[p] = entry(p, "generated", gen[p], data)
        elif p in up:
            out[p] = entry(p, "upstream", up[p], data)
        elif matches(p, SPEC["lexlean"]["paths"]):
            out[p] = entry(p, "lexlean", None, data)
        elif any(p.startswith(m) for m in SPEC["model"]):
            out[p] = entry(p, "model", None, data)
        else:
            out[p] = entry(p, "hand", None, data)
    return out


def render(entries):
    lines = ['{', f'  "spec": "{SPEC["spec"]}",', '  "files": [']
    rows = [json.dumps(entries[p], sort_keys=False) for p in sorted(entries)]
    lines += ["    " + r + ("," if i < len(rows) - 1 else "") for i, r in enumerate(rows)]
    lines += ["  ]", "}"]
    return "\n".join(lines) + "\n"


def load(text):
    return {e["path"]: e for e in json.loads(text)["files"]}


def totals(entries):
    t = {}
    for e in entries.values():
        if e["is"] == "hand":
            c = t.setdefault(e["class"], {"files": 0, "lines": 0})
            c["files"] += 1
            c["lines"] += e["lines"] or 0
    return t


def base_ref():
    ref = opt("--base")
    if ref is None:
        if git("rev-parse", "--verify", "-q", "origin/main", check=False).returncode != 0:
            fail(["no origin/main to ratchet against: fetch it, or name the base with --base REF"])
        head = git("rev-parse", "HEAD").stdout.decode().strip()
        mb = git("merge-base", "HEAD", "origin/main").stdout.decode().strip()
        if mb != head:
            return mb
        if git("rev-parse", "--verify", "-q", "HEAD^1", check=False).returncode != 0:
            return None
        return "HEAD^1"
    return ref


def measure_base(ref):
    """The base revision measured the same way, with this revision's spec: no
    ledger is committed, so no pull request has one to keep current."""
    wt = (ROOT / "target").resolve() / "handwritten-base"
    git("worktree", "remove", "--force", str(wt), check=False)
    shutil.rmtree(wt, ignore_errors=True)
    git("worktree", "add", "-q", "--detach", str(wt), ref)
    try:
        (wt / "target").symlink_to((ROOT / "target").resolve())
        with tempfile.NamedTemporaryFile(suffix=".json") as out:
            r = subprocess.run([sys.executable, "-I", __file__, "--root", str(wt), "--spec", str(ROOT / SPEC_PATH), "--tolerant", "--emit", out.name], capture_output=True)
            if r.returncode != 0:
                fail([f"measuring {ref} failed:", r.stderr.decode(errors="replace")[-2000:]])
            return {e["path"]: e for e in json.loads(pathlib.Path(out.name).read_text())}
    finally:
        git("worktree", "remove", "--force", str(wt), check=False)


def declared(spec):
    """What the spec says without proof: everything except producers, whose
    claims the measure checks by running them."""
    return {
        "model": spec["model"],
        "lexlean": spec["lexlean"]["paths"],
        "plugins": spec.get("plugins", {}).get("paths", []),
        "built": [p for b in spec["built"] for p in b["paths"]],
        "upstream": [json.dumps(spec["upstream"], sort_keys=True)],
    }


def widened(ref):
    """Both trees are measured with this revision's spec, so a declaration that
    reclassifies files (a wider model root, a new plug-in or built path) would
    hide hand-written code from both: none may be added since the base."""
    then = declared(json.loads(git("show", f"{ref}:{SPEC_PATH}").stdout.decode()))
    now = declared(SPEC)
    return [f"{SPEC_PATH}: {k} gained {sorted(set(now[k]) - set(then[k]))} since {ref}; a declaration may only narrow"
            for k in now if set(now[k]) - set(then[k])]


def ratchet(now, base, ref):
    refusals = []
    for p, e in sorted(now.items()):
        plugin = matches(p, SPEC.get("plugins", {}).get("paths", []))
        if e["is"] == "hand" and not plugin and (p not in base or base[p]["is"] != "hand"):
            refusals.append(f"{p}: a new hand-written part (it was {base[p]['is'] if p in base else 'absent'} at {ref}); author it in LexLean (app/src/**/*.lex.tex), built by PrismPM, instead")
        elif e["is"] == "hand" and not plugin and e["lines"] is None and e.get("blob") != base[p].get("blob"):
            refusals.append(f"{p}: a hand-made binary changed; it must come from a producer")
    # The whole, as verdant counts it (maxHandwrittenGameNonCommentLines): a
    # part may move from one class to another, say from the page into its
    # producer, as long as less is written by hand in all.
    tn, tb = totals(now), totals(base)
    total_now = sum(v["lines"] for v in tn.values())
    total_base = sum(v["lines"] for v in tb.values())
    if total_now > total_base:
        grew = ", ".join(f"{c} {tb.get(c, {'lines': 0})['lines']} -> {v['lines']}" for c, v in sorted(tn.items()) if v["lines"] > tb.get(c, {"lines": 0})["lines"])
        refusals.append(f"hand-written lines grew from {total_base} to {total_now} since {ref} ({grew}); hand-written code may only shrink; move it into LexLean")
    return refusals


def report(entries, path):
    t = totals(entries)
    kinds = {}
    for e in entries.values():
        kinds[e["is"]] = kinds.get(e["is"], 0) + 1
    out = ["# Hand-written parts of the Prism", "",
           f"Measured by `tools/handwritten/gate.py` (HW-01) from `{SPEC_PATH}`.", "",
           "| Provenance | Files |", "| --- | ---: |"]
    out += [f"| {k} | {v} |" for k, v in sorted(kinds.items())]
    out += ["", "| Hand-written class | Files | Non-comment lines |", "| --- | ---: | ---: |"]
    out += [f"| {c} | {v['files']} | {v['lines']} |" for c, v in sorted(t.items(), key=lambda x: -x[1]["lines"])]
    out += [f"| **all** | {sum(v['files'] for v in t.values())} | {sum(v['lines'] for v in t.values())} |", ""]
    for c in sorted(t, key=lambda x: -t[x]["lines"]):
        out += [f"## {c}", "", "| File | Lines |", "| --- | ---: |"]
        rows = sorted((e for e in entries.values() if e["is"] == "hand" and e["class"] == c), key=lambda e: -(e["lines"] or 0))
        out += [f"| `{e['path']}` | {e['lines'] if e['lines'] is not None else 'binary'} |" for e in rows]
        out.append("")
    pathlib.Path(path).write_text("\n".join(out))


def lint():
    """What can be checked without running producers or the network (the
    conformance suite): every producer can be found, every tools/*/gen.py is a
    producer, and every tracked file has a class."""
    bad = []
    named = {a for prod in SPEC["producers"] for a in prod["run"]}
    for prod in SPEC["producers"]:
        script = next((a for a in prod["run"] if a.endswith((".py", ".mjs", ".sh"))), None)
        if script and not (ROOT / script).exists():
            bad.append(f"producer {prod['id']}: {script} does not exist")
    for gen in sorted(ROOT.glob("tools/*/gen.py")):
        rel = gen.relative_to(ROOT).as_posix()
        if rel not in named:
            bad.append(f"{rel} is a generator that no producer of {SPEC_PATH} runs")
    for p in tracked():
        if not matches(p, SPEC["lexlean"]["paths"]) and not any(p.startswith(m) for m in SPEC["model"]):
            class_of(p)
    if bad:
        fail(bad)
    print(f"HW-01: {len(SPEC['producers'])} producers, every generator among them")


def main():
    if "--lint" in ARGS:
        return lint()
    now = measure()
    if opt("--emit"):
        pathlib.Path(opt("--emit")).write_text(json.dumps(list(now.values())))
        return
    refusals, ref = [], base_ref() if CHECK else None
    if ref and git("cat-file", "-e", f"{ref}:{SPEC_PATH}", check=False).returncode != 0:
        print(f"HW-01: {ref} has no {SPEC_PATH}: HW-01 starts here, nothing to ratchet against")
        ref = None
    if ref:
        refusals = widened(ref) + ratchet(now, measure_base(ref), ref)
    if opt("--report"):
        report(now, opt("--report"))
    if opt("--ledger"):
        pathlib.Path(opt("--ledger")).write_text(render(now))
    if refusals:
        fail(refusals)
    t = totals(now)
    lean_ids = {x["id"] for x in SPEC["producers"] + SPEC["built"] if x.get("lexlean")}
    outside_gen = sum(1 for e in now.values() if e["is"] == "generated" and e.get("from") not in lean_ids)
    outside_model = sum(1 for e in now.values() if e["is"] == "model")
    print(f"HW-01: distance from LexLean: {outside_model} model records and {outside_gen} files written by producers outside LexLean")
    print(f"HW-01: {sum(v['files'] for v in t.values())} hand-written files, {sum(v['lines'] for v in t.values())} non-comment lines"
          + (f", none added or grown since {ref}" if ref else ", no base to ratchet against"))
    print(NOTE)

main()
