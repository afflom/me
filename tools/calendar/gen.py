"""The element suite of the iCalendar reader: test/calendar/elements.test.mjs.

The registry itself, site/calendar/registry.mjs, is written in LexLean by
generators/calendar (GenCalendar) from the IANA iCalendar Element Registries
and RFC 5545 section 3, pinned in app/specs/calendar/spec.json, and held by
GN-01. This writes the suite that holds the reader to every element of it
that an oracle example (test/oracle/corpus.json) exercises, and lists the
rest.

usage: python3 -I tools/calendar/gen.py [--check]
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from registry import ROOT, load  # noqa: E402

args = sys.argv[1:]
data = load()
sys.path.insert(0, str(HERE.parent / "oracle"))
import ical  # noqa: E402

TEST = ROOT / "test/calendar/elements.test.mjs"
CORPUS = json.loads((ROOT / "test/oracle/corpus.json").read_text(encoding="utf-8"))["corpus"]


def exercised(reg):
    """Which oracle examples exercise each element: a component it opens, a property, parameter or value type it uses, a registered value it names."""
    use = {}
    add = lambda key, eid: use.setdefault(f"{reg['standard']}-{key}", []).append(eid) if eid not in use.get(f"{reg['standard']}-{key}", []) else None
    for e in CORPUS:
        if e["kind"] not in ("icalLine", "icalObject", "calendar"):
            continue
        row = json.loads(e["raw"]) if e["kind"] != "calendar" else {}
        text = row.get("line") or row.get("ical") or e["raw"]
        for line in ical.lines(text):
            if "invalid" in line:
                continue
            if line["name"] in ("BEGIN", "END"):
                if line["value"].upper() in reg["components"]:
                    add(f"component-{line['value'].upper()}", e["id"])
                continue
            if line["name"] in reg["properties"]:
                add(f"property-{line['name']}", e["id"])
                if line["value"].upper() in reg["properties"][line["name"]].get("registered", []):
                    add(f"enum-{line['name']}-{line['value'].upper()}", e["id"])
            if ical.kind_of(line, reg) in reg["values"]:
                add(f"value-{ical.kind_of(line, reg)}", e["id"])
            for name, values in line["params"].items():
                if name in reg["parameters"]:
                    add(f"parameter-{name}", e["id"])
                    for v in values:
                        if v.upper() in reg["parameters"][name].get("registered", []):
                            add(f"enum-{name}-{v.upper()}", e["id"])
    return dict(sorted(use.items()))


def every(reg):
    s = reg["standard"]
    ids = [f"{s}-component-{k}" for k in reg["components"]] + [f"{s}-property-{k}" for k in reg["properties"]]
    ids += [f"{s}-parameter-{k}" for k in reg["parameters"]] + [f"{s}-value-{k}" for k in reg["values"]]
    ids += [f"{s}-enum-{k}-{v}" for g in ("parameters", "properties") for k, x in reg[g].items() for v in x.get("registered", [])]
    return ids


use = exercised(data)
suite = "\n".join([
    "// Generated by tools/calendar/gen.py from the iCalendar registry (site/calendar/registry.mjs, written by",
    "// generators/calendar from IANA's registries and RFC 5545) and the",
    "// oracle's examples (test/oracle/corpus.json). Do not edit. Each element of the standard that an example",
    "// exercises is held here to the reference reading (tools/oracle/ical.py): the Prism's reader",
    "// (site/calendar/ical.mjs) reads every example that uses it exactly as the reference does.",
    "// usage: node --test test/calendar/elements.test.mjs",
    *[f"// enforces: {i}" for i in use],
    'import assert from "node:assert/strict";',
    'import { spawnSync } from "node:child_process";',
    'import { readFileSync } from "node:fs";',
    'import test from "node:test";',
    'import { registered, spanOf, tree } from "../../site/calendar/ical.mjs";',
    "",
    'const { corpus } = JSON.parse(readFileSync(new URL("../oracle/corpus.json", import.meta.url), "utf8"));',
    "const byId = new Map(corpus.map((e) => [e.id, e]));",
    "const plain = (v) => JSON.parse(JSON.stringify(v));",
    "const textOf = (e) => (e.kind === \"calendar\" ? e.raw : JSON.parse(e.raw).line ?? JSON.parse(e.raw).ical);",
    f"const EXERCISED = {json.dumps(use, indent=1)};",
    "",
    "test(\"this suite is what the registry and the oracle's examples give\", () => {",
    "  const run = spawnSync(\"python3\", [\"-I\", \"tools/calendar/gen.py\", \"--check\"], { encoding: \"utf8\" });",
    "  assert.equal(run.status, 0, run.stderr || run.stdout);",
    "});",
    "",
    "for (const [id, examples] of Object.entries(EXERCISED)) {",
    "  test(id, () => {",
    "    for (const eid of examples) {",
    "      const e = byId.get(eid);",
    "      const got = plain(tree(textOf(e)));",
    "      if (e.kind === \"icalLine\") assert.deepStrictEqual(got.props, e.expect.props, eid);",
    "      else assert.deepStrictEqual(got, e.expect.tree, eid);",
    "      if (e.kind !== \"icalLine\") assert.deepStrictEqual(spanOf(textOf(e)) ?? undefined, e.expect.span, `${eid} span`);",
    "    }",
    "    // A registered value is known as one (its IANA value registry).",
    "    const enumOf = /-enum-([A-Z0-9-]+?)-([A-Z0-9-]+)$/.exec(id);",
    "    if (enumOf) assert.ok(registered(enumOf[1], enumOf[2]), id);",
    "  });",
    "}",
    "",
    "test(\"every element of the standard is exercised here or listed as not yet exercised\", () => {",
    f"  const every = {json.dumps(every(data))};",
    "  const missing = every.filter((id) => !(id in EXERCISED));",
    f"  assert.deepStrictEqual(missing, {json.dumps([i for i in every(data) if i not in use])}, \"what no example exercises changed: regenerate\");",
    "});",
    "",
])

if "--check" in args:
    if not TEST.exists() or TEST.read_text(encoding="utf-8") != suite:
        sys.exit("calendar: test/calendar/elements.test.mjs is stale: run python3 -I tools/calendar/gen.py")
    sys.exit(0)
TEST.parent.mkdir(parents=True, exist_ok=True)
TEST.write_text(suite, encoding="utf-8")
print(f"calendar: {len(data['components'])} components, {len(data['properties'])} properties, {len(data['parameters'])} parameters, {len(data['values'])} value types of {data['standard']}; {len(use)} of {len(every(data))} elements exercised by an example")
