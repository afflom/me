//! The `person` suite: `features/suites/person.feature`.
//!
//! The behaviour runs in `pages.yml` with every `*.test.mjs`:
//! `test/person/icf.test.mjs` re-derives the whole-person model from the ICF
//! release the oracle pins and plants a defect for each check. This test holds
//! the wiring fixed.

use std::path::PathBuf;

fn read(path: &str) -> String {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .expect("crates/conformance is two below the root")
        .to_path_buf();
    std::fs::read_to_string(root.join(path)).expect(path)
}

/// `WP-01`: The whole-person model is every entity of WHO's ICF release pinned by checksum, with its code, title and URI as WHO publishes it
#[test]
fn person_wp_01() {
    let generator = read("tools/person/gen.py") + &read("tools/standards/abnf.py");
    for needle in [
        "not the pinned",
        "def workbook",
        "def tabulation",
        "is stale",
        "the planted defect was not refused",
    ] {
        assert!(
            generator.contains(needle),
            "WP-01: gen.py must contain `{needle}`"
        );
    }
    let test = read("test/person/icf.test.mjs");
    for needle in ["\"--check\"", "\"--plant\"", "PLANTED", "terms 1.2.3"] {
        assert!(
            test.contains(needle),
            "WP-01: icf.test.mjs must contain `{needle}`"
        );
    }
    let spec = read("app/specs/oracle/spec.json");
    assert!(
        spec.contains("\"classifications\"") && spec.contains("\"model\": \"site/person/icf.mjs\""),
        "WP-01: the oracle pins the ICF release and names its model"
    );
    assert!(
        read("model/authorities.toml").contains("realized_by = [\"WP-01\"]"),
        "WP-01: the ICF release is a cited authority whose evidence is this ID"
    );
    assert!(
        read("site/person/icf.mjs").contains("Generated by tools/person/gen.py"),
        "WP-01: the page's model is the generated one"
    );
}
